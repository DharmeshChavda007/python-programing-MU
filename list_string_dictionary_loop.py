'''Write a program to iterate over lists strings and
dictionaries using loops. '''
# iterate list
lst = ['Dharmesh','Rohan','Rahul','Bharat']

for i in lst:
    print(i)

print('========================================')

# iterate string
name = "Dharmesh"

for t in name:
    print(t)

print('========================================')

